// Bundles src/worker-entry.ts, wasm inlined, into one script and writes it
// as a string module to src/generated/worker-source.js, so the session can
// start a blob worker with no second file. Runs before tsc in the build.
import { mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { build } from "rolldown";

const pkg = resolve(import.meta.dirname, "..");
const out = await build({
  input: join(pkg, "src", "worker-entry.ts"),
  output: { format: "iife", codeSplitting: false },
  transform: { define: { "import.meta": "{}" } },
  write: false,
  logLevel: "warn",
});
const code = out.output[0].code;
mkdirSync(join(pkg, "src", "generated"), { recursive: true });
writeFileSync(join(pkg, "src", "generated", "worker-source.js"), `// generated by scripts/prebuild.mjs\nexport const workerSource = ${JSON.stringify(code)};\n`);
console.log(`prebuild: ${code.length} bytes (measured)`);
