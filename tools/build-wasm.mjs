// build-wasm: compiles crates/<crate> to wasm32 with SIMD128 through
// wasm-pack (--target web) into packages/<pkg>/src/wasm, then writes
// inline.js, the same bytes as base64, so a single file build runs from
// file:// with no fetch.
// Usage: node tools/build-wasm.mjs <package-name>
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";
import { gzipSync } from "node:zlib";

const name = process.argv[2];
if (!name) {
  console.error("usage: node tools/build-wasm.mjs <package-name>");
  process.exit(2);
}
const root = resolve(import.meta.dirname, "..");
const crate = join(root, "crates", name);
const out = join(root, "packages", name, "src", "wasm");
const stem = name.replace(/-/g, "_");

// the rustup toolchain carries the wasm32 target; a Homebrew rustc earlier on PATH does not
const rustupBin = join(homedir(), ".cargo", "bin");
const env = { ...process.env };
if (existsSync(rustupBin)) env.PATH = `${rustupBin}:${env.PATH}`;

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
const args = ["build", crate, "--target", "web", "--release", "--no-pack", "--out-dir", out, "--out-name", stem, "--", "--features", "wasm"];
const run = spawnSync("wasm-pack", args, { stdio: "inherit", env });
if (run.status !== 0) {
  console.error(`build-wasm: wasm-pack failed for ${name}`);
  process.exit(run.status ?? 1);
}
rmSync(join(out, ".gitignore"), { force: true });
const bytes = readFileSync(join(out, `${stem}_bg.wasm`));
writeFileSync(
  join(out, "inline.js"),
  `// generated by tools/build-wasm.mjs; the ${name} wasm as base64\n` +
    `export const wasmBase64 = "${bytes.toString("base64")}";\n` +
    `export function wasmBytes() {\n` +
    `  const s = atob(wasmBase64);\n` +
    `  const b = new Uint8Array(s.length);\n` +
    `  for (let i = 0; i < s.length; i++) b[i] = s.charCodeAt(i);\n` +
    `  return b;\n` +
    `}\n`,
);
writeFileSync(join(out, "inline.d.ts"), "export declare const wasmBase64: string;\nexport declare function wasmBytes(): Uint8Array;\n");
const gz = gzipSync(bytes, { level: 9 }).length;
console.log(`build-wasm: ${name} ${bytes.length} bytes, ${gz} gzip (measured)`);
